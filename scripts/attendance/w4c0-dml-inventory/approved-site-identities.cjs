// #4556 W4C-0 Stage D — the frozen APPROVED SITE IDENTITY table for the §8.4 mechanical bypass
// guard.
//
// WHY THIS FILE EXISTS (replaces whole-file / path-prefix / broad-symbol approval)
// -------------------------------------------------------------------------------
// The previous model approved DML by *predicate*: `site.relPath === '<file>'`,
// `relPath.startsWith('<prefix>')`, or `bySymbol(file, /regex/)` with no table/verb constraint.
// Once such a predicate hit, the rest of the audit was skipped for that file, so a brand-new
// `INSERT INTO attendance_records` added to an already-approved file (for example the generic
// after-sales approval bridge) was admitted silently and the exact-head HEAD scan still passed.
//
// The fix is NOT to add more recognised cases to those predicates. It is to delete the predicates
// and make approval attach to an exact, derived SITE IDENTITY with a pinned multiplicity:
//
//     identity  = (relPath, enclosingSymbol, table, verb)
//     approval  = that identity appears in this table
//     amount    = it may occur EXACTLY `occurrences` times in the census, no more, no fewer
//
// Consequences inside an already-approved file:
//   - a NEW table            -> new identity -> not in this table -> unclaimed        -> RED
//   - a NEW verb             -> new identity -> not in this table -> unclaimed        -> RED
//   - a NEW symbol           -> new identity -> not in this table -> unclaimed        -> RED
//   - a SECOND occurrence of an already-approved identity -> observed > occurrences   -> RED
//   - a REMOVED occurrence   -> observed < occurrences (stale approval)               -> RED
//
// There is exactly ONE recognition rule (map lookup + count comparison). This table is data
// derived from the scan itself, not classifier logic: there is no shape a future write can take
// that "falls through" to a broader claim, because there is no broader claim.
//
// PROVENANCE: derived once, mechanically, from the live census at the conversion commit, using
// the predicates it replaces. The conversion is claim-preserving BY CONSTRUCTION — it does not
// re-adjudicate whether any of these sites *should* be approved; it only makes each approval
// exact and counted. Every row's `entryIds` is exactly the set of curated debt entries whose old
// predicate claimed that identity (the derivation aborted on any heterogeneous or unclaimed
// site; there were none). Rows with an empty `entryIds` and a `genericSharedReason` are the
// former non-attendance generic-shared-function allowlist, converted from whole-file to tuple.
//
// STATED RESIDUE (see the collector's own header for the scanner's limitations):
//   - `enclosingSymbol` is the collector's nearest-preceding-declaration heuristic, not AST
//     attribution. Two genuinely different call sites that share a helper name collapse into one
//     identity, so SUBSTITUTING an illegitimate write for a legitimate one at the very same
//     (file, symbol, table, verb) does not red. Multiplicity pinning bounds ADDITIONS, not swaps.
//   - The `debtKey` 50-line block index is deliberately NOT part of this identity: it would red
//     on unrelated line shifts. Multiplicity, not block index, is what separates repeated sites.
//   - CASE, on two separate axes. The scanner's DML pattern matches KEYWORDS case-sensitively, so
//     a lowercase or mixed-case SQL keyword stays invisible — that residue is unchanged. The TABLE
//     IDENTIFIER is a different axis and is NOT case-sensitive: it is resolved by PostgreSQL
//     folding rules (unquoted folds, so `ATTENDANCE_RECORDS` is the same relation AND the same
//     site identity as `attendance_records`; double-quoted is preserved, so `"Attendance_Records"`
//     is a different relation and reds as an unclassified attendance-owned table). One consequence
//     is worth saying out loud rather than leaving to be discovered: because an uppercase spelling
//     resolves onto the SAME identity, SUBSTITUTING an approved lowercase write with its uppercase
//     spelling stays green — same relation, same pinned count. That is the substitution residue
//     already stated above, not a second hole; ADDING an uppercase write reds on multiplicity.
//
// This file lives inside `scripts/attendance/w4c0-dml-inventory/`, which the collector excludes
// from its own scan, so the literal table names below are data and never mint census sites.

