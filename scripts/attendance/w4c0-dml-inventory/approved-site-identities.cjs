/**
 * Injective identity key for a census site.
 *
 * JSON-array encoding rather than a `::`-joined string: a joined key lets a symbol that itself
 * contains the separator alias a DIFFERENT (relPath, enclosingSymbol, table, verb) tuple, which
 * would be an approval-widening bug in the very thing this module exists to make exact. Route
 * symbols are collector-generated from arbitrary path strings, so this is not hypothetical.
 */
function siteIdentityKey(site) {
  return JSON.stringify([site.relPath, site.enclosingSymbol, site.table, site.verb])
}

/** Human-readable form used only in failure messages — never as a lookup key. */
function siteIdentityLabel(site) {
  return `${site.relPath} :: ${site.enclosingSymbol} :: ${site.table}:${site.verb}`
}

const APPROVED_SITE_IDENTITY_BY_KEY = new Map()
for (const row of APPROVED_SITE_IDENTITIES) {
  const key = siteIdentityKey(row)
  if (APPROVED_SITE_IDENTITY_BY_KEY.has(key)) {
    throw new Error(`ATTENDANCE_W4C0_APPROVED_SITE_IDENTITY_DUPLICATE: ${siteIdentityLabel(row)}`)
  }
  if (!Number.isInteger(row.occurrences) || row.occurrences < 1) {
    throw new Error(`ATTENDANCE_W4C0_APPROVED_SITE_IDENTITY_BAD_MULTIPLICITY: ${siteIdentityLabel(row)}`)
  }
  const hasEntryIds = Array.isArray(row.entryIds) && row.entryIds.length > 0
  const hasGenericReason = typeof row.genericSharedReason === 'string' && row.genericSharedReason.length > 0
  if (hasEntryIds === hasGenericReason) {
    // Exactly one disposition per identity: owned by curated debt entries, or generic-shared.
    // Both (or neither) would let a row be approved without a named owner.
    throw new Error(`ATTENDANCE_W4C0_APPROVED_SITE_IDENTITY_AMBIGUOUS_DISPOSITION: ${siteIdentityLabel(row)}`)
  }
  APPROVED_SITE_IDENTITY_BY_KEY.set(key, { ...row, key })
}

const APPROVED_IDENTITY_KEYS_BY_ENTRY_ID = new Map()
for (const row of APPROVED_SITE_IDENTITY_BY_KEY.values()) {
  for (const entryId of row.entryIds || []) {
    if (!APPROVED_IDENTITY_KEYS_BY_ENTRY_ID.has(entryId)) {
      APPROVED_IDENTITY_KEYS_BY_ENTRY_ID.set(entryId, new Set())
    }
    APPROVED_IDENTITY_KEYS_BY_ENTRY_ID.get(entryId).add(row.key)
  }
}

const GENERIC_SHARED_IDENTITY_KEYS = new Set(
  [...APPROVED_SITE_IDENTITY_BY_KEY.values()]
    .filter((row) => row.genericSharedReason)
    .map((row) => row.key),
)

/** Identity keys approved for one curated debt entry id (empty set for metadata-only entries). */
function approvedIdentityKeysForEntry(entryId) {
  return APPROVED_IDENTITY_KEYS_BY_ENTRY_ID.get(entryId) || new Set()
}

