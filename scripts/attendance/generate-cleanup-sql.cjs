#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * W4C-3c P15 — privileged generated cleanup for attendance import source tags.
 *
 * NEVER emits DELETE against attendance_records for W4-backed rows.
 * Emits a target inventory + ops_retirement instructions. Tooling-only non-W4
 * fixture teardown must call assertToolingOnlyNonW4FixtureTeardownAllowedV1
 * (packages/core-backend/src/attendance/w4c3c-ops-retirement.ts) before any
 * destructive fixture SQL.
 *
 * Safe to require() from tests: CLI runs only when this file is the process entry.
 */
const fs = require('fs/promises')

function escapeLiteral(value) {
  return String(value).replace(/'/g, "''")
}

function buildCleanupSql(options = {}) {
  const orgId = String(options.orgId || options.org || '').trim()
  const source = options.source || ''
  const from = options.from || ''
  const to = options.to || ''
  if (!orgId) {
    const error = new Error('Missing --org')
    error.code = 'ATTENDANCE_P15_ORG_REQUIRED'
    throw error
  }
  if (!source) {
    const error = new Error('Missing --source (e.g. dingtalk_csv_test)')
    error.code = 'ATTENDANCE_P15_SOURCE_REQUIRED'
    throw error
  }

  const where = []
  where.push(`e.org_id = '${escapeLiteral(orgId)}'`)
  where.push(`e.source = '${escapeLiteral(source)}'`)
  if (from) where.push(`e.occurred_at >= '${escapeLiteral(from)}'`)
  if (to) where.push(`e.occurred_at < '${escapeLiteral(to)}'`)
  const whereSql = where.join(' AND ')

  // Intentionally NO live record delete DML. W4-backed parents retire through
  // ops_retirement. Executable runner:
  //   node scripts/attendance/execute-ops-retirement-cleanup.cjs --source ... --org ...
  const sql = `-- W4C-3c P15 operator cleanup plan (canonical ops_retirement)
-- Generated by scripts/attendance/generate-cleanup-sql.cjs
-- Source tag: ${source}
-- Org: ${orgId}
--
-- Executable path (not comments-only):
--   node scripts/attendance/execute-ops-retirement-cleanup.cjs \\
--     --source ${source} --org ${orgId}${from ? ` --from ${from}` : ''}${to ? ` --to ${to}` : ''}
--
-- Dry-run inventory only:
--   node scripts/attendance/execute-ops-retirement-cleanup.cjs \\
--     --source ${source} --org ${orgId} --dry-run

BEGIN;

SELECT DISTINCT r.id AS record_id,
       r.org_id,
       r.user_id,
       r.work_date,
       r.current_calculation_id,
       r.projection_owner,
       r.visibility_state,
       r.visibility_reason,
       CASE
         WHEN r.current_calculation_id IS NOT NULL
           OR r.projection_owner IS DISTINCT FROM 'legacy_untracked'
           OR EXISTS (
             SELECT 1
               FROM attendance_record_calculations c
              WHERE c.attendance_record_id = r.id
                AND c.org_id = r.org_id
           )
           THEN 'ops_retirement_required'
         ELSE 'tooling_only_non_w4_fixture_teardown_guard_required'
       END AS cleanup_path
  FROM attendance_events e
  JOIN attendance_records r
    ON r.org_id = e.org_id
   AND r.user_id = e.user_id
   AND r.work_date = e.work_date
 WHERE ${whereSql};

COMMIT;
`

  // Structural live-DML probe: comment-masked scan (same as the collector), not regex
  // over raw comment text.
  let forbidsRecordDelete = true
  try {
    const { hasLiveDmlOnTable } = require('./w4c0-dml-inventory/collector.cjs')
    forbidsRecordDelete = !hasLiveDmlOnTable(sql, 'delete', 'attendance_records')
  } catch {
    // Fallback when required outside the monorepo layout: strip SQL line comments only.
    const withoutSqlComments = String(sql)
      .split(/\r?\n/)
      .map((line) => line.replace(/--.*$/, ''))
      .join('\n')
    forbidsRecordDelete = !/\bDELETE\s+FROM\s+attendance_records\b/i.test(withoutSqlComments)
  }

  return {
    sql,
    forbidsRecordDelete,
    requiresOpsRetirement: /ops_retirement/i.test(sql),
    orgId,
    source,
  }
}

function main(argv = process.argv.slice(2)) {
  const getArg = (name, fallback) => {
    const flag = `--${name}`
    const idx = argv.findIndex((value) => value === flag || value.startsWith(`${flag}=`))
    if (idx === -1) return fallback
    const raw = argv[idx]
    if (raw.includes('=')) return raw.slice(flag.length + 1)
    const next = argv[idx + 1]
    if (!next || next.startsWith('--')) return true
    return next
  }

  const source = getArg('source', '')
  const orgId = getArg('org', '')
  const from = getArg('from', '')
  const to = getArg('to', '')
  const outFile = getArg('file', '')

  let plan
  try {
    plan = buildCleanupSql({ source, orgId, from, to })
  } catch (error) {
    console.error(error.message || error)
    process.exit(1)
  }

  if (outFile) {
    return fs.writeFile(outFile, plan.sql, 'utf-8')
      .then(() => console.log(outFile))
      .catch((error) => {
        console.error(error)
        process.exit(1)
      })
  }
  console.log(plan.sql)
  return undefined
}

module.exports = {
  buildCleanupSql,
  ATTENDANCE_P15_NO_RECORD_DELETE: true,
  main,
}

if (require.main === module) {
  main()
}
