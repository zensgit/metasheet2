#!/usr/bin/env node
/**
 * H-6 (2026-09-22, widened round 2 2026-09-22) — generate / check the committed token-set
 * manifest for the required web lane's `vitest run` invocations.
 *
 * See docs/development/required-web-lane-token-manifest-guard-design-20260922.md for the full
 * design (option comparison, threat model, round-2 scope widening). Short version: the lane's
 * positional token filters can silently lose a token (rebase mistake, bad manual edit, a
 * "cleanup" that deletes the wrong line) while the lane itself stays green — nothing currently
 * asserts the SET of tokens the script hands vitest against any independent record. This manifest
 * is that independent record: a plain, sorted, one-token-per-line file (plus a `#`-prefixed
 * provenance header — comment lines are ignored by both readers below) committed alongside the
 * script, and a vitest guard
 * (packages/core-backend/tests/unit/required-web-lane-token-manifest-guard.test.ts) that fails
 * when the two sets diverge in either direction.
 *
 * ROUND 2 SCOPE (independent gate review round 1, P1-1, option (a) — selected during
 * implementation on the round-1 reviewer's own framing that only (a) closes the residual; NOT an
 * owner ruling — `gh pr view 5974 --json comments,reviews` → 0 comments, 0 reviews — owner
 * disposition is pending and option (b) remains a fallback): round 1 covered only the script's
 * final `exec npx vitest run …` line (397 tokens). The review found 18 MORE `npx vitest run …`
 * lines earlier in the same script, gated by the same `set -euo pipefail`, carrying 102 more
 * distinct tokens (round 1 counted 28 pinned by no other guard; round 2's gate review found a
 * sixth lane-reading guard the census had missed, correcting the residual to ≤24 — see the design
 * doc §1). This generator now unions the token set of ALL 19 gating lines (`allVitestTokens()`,
 * `scripts/ops/required-web-lane-exec-block.mjs`) — 499 tokens total, not just the exec block's 397.
 *
 * This script only produces/checks the manifest file; it is not itself the guard — CI does not
 * invoke it. Run it locally after editing any of the 19 gating lines:
 *
 *   node scripts/ops/required-web-lane-token-manifest.mjs           # check only, exits 1 on drift
 *   node scripts/ops/required-web-lane-token-manifest.mjs --write   # regenerate the manifest file
 *
 * Values-free: reads only repo-tracked script text, writes only token names, one per line, plus a
 * static provenance header.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { allVitestInvocations, allVitestTokens } from './required-web-lane-exec-block.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '..', '..')
const LANE_SCRIPT = join(REPO_ROOT, 'apps', 'web', 'scripts', 'run-required-web-tests.sh')
const MANIFEST_PATH = join(REPO_ROOT, 'apps', 'web', 'scripts', 'run-required-web-tests.tokens')
const RELATIVE_MANIFEST_PATH = 'apps/web/scripts/run-required-web-tests.tokens'
const RELATIVE_LANE_SCRIPT = 'apps/web/scripts/run-required-web-tests.sh'

/**
 * Static provenance header written by `--write`. `#`-prefixed lines are ignored by both this
 * script's own reader (below) and the guard test's `manifestTokens()` — a `#` line is never
 * mistaken for a token (P3-5, round-1 gate review).
 */
const HEADER_LINES = [
  `# generated by: node scripts/ops/${'required-web-lane-token-manifest.mjs'} --write`,
  '# do not hand-edit this file — regenerate via the command above and commit the result in the',
  '# SAME PR that changed the tokens.',
  `# scope (round 2, 2026-09-22): the union of the positional filter tokens of every gating`,
  `# \`vitest run\` logical line in ${RELATIVE_LANE_SCRIPT} — not only its final \`exec\` line.`,
  '# See docs/development/required-web-lane-token-manifest-guard-design-20260922.md §1.',
]

const caseInsensitive = (a, b) => {
  const la = a.toLowerCase()
  const lb = b.toLowerCase()
  if (la !== lb) return la < lb ? -1 : 1
  return a < b ? -1 : a > b ? 1 : 0
}

function readManifestTokens() {
  let raw
  try {
    raw = readFileSync(MANIFEST_PATH, 'utf8')
  } catch (err) {
    if (err && err.code === 'ENOENT') return []
    throw err
  }
  return raw
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('#'))
}

function activeTokens() {
  const script = readFileSync(LANE_SCRIPT, 'utf8')
  return allVitestTokens(script)
}

function invocationCount() {
  const script = readFileSync(LANE_SCRIPT, 'utf8')
  return allVitestInvocations(script).length
}

function main(argv) {
  const write = argv.includes('--write')

  const activeSet = activeTokens()
  const sorted = [...activeSet].sort(caseInsensitive)
  const gatingLines = invocationCount()

  if (write) {
    writeFileSync(MANIFEST_PATH, `${HEADER_LINES.join('\n')}\n${sorted.join('\n')}\n`, 'utf8')
    console.log(
      `wrote ${sorted.length} tokens to ${RELATIVE_MANIFEST_PATH} `
      + `(union of ${gatingLines} gating \`vitest run\` invocations in ${RELATIVE_LANE_SCRIPT}, `
      + `${activeSet.size} distinct).`,
    )
    return 0
  }

  const manifestTokens = readManifestTokens()
  const manifestSet = new Set(manifestTokens)

  const missing = [...manifestSet].filter((t) => !activeSet.has(t)).sort(caseInsensitive)
  const extra = [...activeSet].filter((t) => !manifestSet.has(t)).sort(caseInsensitive)

  console.log(`active (${gatingLines} gating invocations): ${activeSet.size} distinct tokens`)
  console.log(`committed manifest: ${manifestTokens.length} tokens, ${manifestSet.size} distinct`)

  if (missing.length === 0 && extra.length === 0) {
    console.log('MANIFEST MATCHES — the committed token set equals the active token set.')
    return 0
  }
  if (missing.length) {
    console.log(
      `MISSING FROM ACTIVE (${missing.length}) — in the manifest but no longer produced by any `
      + `gating invocation, i.e. silently dropped from the lane: ${missing.join(' ')}`,
    )
  }
  if (extra.length) {
    console.log(
      `EXTRA IN ACTIVE (${extra.length}) — produced by a gating invocation but not yet recorded `
      + `in the manifest, run with --write and commit the result: ${extra.join(' ')}`,
    )
  }
  return 1
}

process.exit(main(process.argv.slice(2)))
