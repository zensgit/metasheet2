export function notificationReason(code: string | null, text: NotificationText): string {
  if (code !== null && Object.prototype.hasOwnProperty.call(NOTIFICATION_REASON_KEYS, code)) {
    return text[NOTIFICATION_REASON_KEYS[code as keyof typeof NOTIFICATION_REASON_KEYS]]
  }
  return text.reasonUnknown
}

export function notificationProviderName(provider: string, text: NotificationText): string {
  return provider === 'dingtalk' ? text.providerDingtalk : provider
}
