function receivingRunner(): AuthorizationInputTransactionRunner {
  return (handler) => {
    const pool = testPool
    if (!pool) throw new Error('receiving pool is not open')
    return (async () => {
      const client = await pool.connect()
      try {
        await client.query('BEGIN')
        try {
          const value = await handler({
            query: (text, params) => client.query(text, params),
            __rawClient: client,
          })
          await client.query('COMMIT')
          return value
        } catch (error) {
          await client.query('ROLLBACK').catch(() => undefined)
          throw error
        }
      } finally {
        client.release()
      }
    })()
  }
}

function kyselyOnOpenClient(client: PoolClient): Kysely<unknown> {
  const bound = {
    query: (text: string, values?: unknown[]) => client.query(text, values),
    release: () => undefined,
  }
  return new Kysely<unknown>({
    dialect: new PostgresDialect({
      pool: {
        connect: () => Promise.resolve(bound),
        end: () => Promise.resolve(),
      } as Pool,
    }),
  })
}

async function waitUntilBlockedBy(blockerPid: number): Promise<number> {
  const deadline = Date.now() + 3500
  while (Date.now() < deadline) {
    const blocked = await adminPool!.query(
      `SELECT pid FROM pg_stat_activity
        WHERE pid <> $1 AND state = 'active' AND wait_event_type = 'Lock'
          AND $1 = ANY(pg_blocking_pids(pid))
        ORDER BY pid`,
      [blockerPid],
    )
    const waiter = blocked.rows[0]?.pid
    if (waiter !== undefined && waiter !== null) return Number(waiter)
    await new Promise((resolve) => setTimeout(resolve, 15))
  }
  throw new Error('timed out waiting for a backend to block on the owned lock')
}

async function waitUntilWaiting(waiterPid: number): Promise<void> {
  const deadline = Date.now() + 3500
  while (Date.now() < deadline) {
    const blocked = await adminPool!.query(
      `SELECT count(*)::int AS waiting
         FROM pg_stat_activity
        WHERE pid = $1 AND state = 'active' AND wait_event_type = 'Lock'
          AND cardinality(pg_blocking_pids(pid)) > 0`,
      [waiterPid],
    )
    if (Number(blocked.rows[0]?.waiting ?? 0) === 1) return
    await new Promise((resolve) => setTimeout(resolve, 15))
  }
  throw new Error('timed out waiting for the second connection to block')
}

async function waitUntilUserRolesReadBlocked(
  holderPid: number,
  relationOid: string,
): Promise<{ waiterPid: number; query: string }> {
  const deadline = Date.now() + 3500
  while (Date.now() < deadline) {
    const blocked = await adminPool!.query(
      `SELECT a.pid, a.query
         FROM pg_stat_activity a
        WHERE a.pid <> $1
          AND a.state = 'active'
          AND a.wait_event_type = 'Lock'
          AND $1 = ANY(pg_blocking_pids(a.pid))
          AND position('user_roles' in a.query) > 0
          AND position('directory_integrations' in a.query) = 0`,
      [holderPid],
    )
    const row = blocked.rows[0]
    if (row) {
      const waiterPid = Number(row.pid)
      const locks = await adminPool!.query(
        `SELECT pid, mode, granted
           FROM pg_locks
          WHERE relation = $1::oid
            AND pid = ANY($2::int[])`,
        [relationOid, [holderPid, waiterPid]],
      )
      const holderGranted = locks.rows.some((lock) => (
        Number(lock.pid) === holderPid && lock.mode === 'AccessExclusiveLock' && lock.granted === true
      ))
      const waiterWaiting = locks.rows.some((lock) => Number(lock.pid) === waiterPid && lock.granted === false)
      if (holderGranted && waiterWaiting) return { waiterPid, query: String(row.query) }
    }
    await new Promise((resolve) => setTimeout(resolve, 15))
  }
  throw new Error('timed out waiting for the privilege read to block on user_roles')
}

type Observed<T> = { ok: true; value: T } | { ok: false; error: unknown }

function observe<T>(promise: Promise<T>): Promise<Observed<T>> {
  return promise.then(
    (value) => ({ ok: true, value }),
    (error: unknown) => ({ ok: false, error }),
  )
}

function observedValue<T>(observed: Observed<T>): T {
  if (observed.ok === false) throw observed.error
  return observed.value
}

