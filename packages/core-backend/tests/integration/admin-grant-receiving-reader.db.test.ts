  async function liveAssessment(userId: string): Promise<{
    privilegeWitness: string
    privilegeClass: 'standard' | 'high'
  }> {
    const client = await testPool!.connect()
    let open = false
    try {
      await client.query('BEGIN')
      open = true
      const assessment = await assessSecurityActionPrivilege({
        query: async (statement: string, params?: unknown[]) => {
          const result = await client.query(statement, params)
          return { rows: result.rows, rowCount: result.rowCount ?? null }
        },
      }, userId)
      await client.query('COMMIT')
      open = false
      if (assessment.privilegeClass !== 'standard' && assessment.privilegeClass !== 'high') {
        throw new Error('fixture actor class was not assessed')
      }
      return { privilegeWitness: assessment.witness, privilegeClass: assessment.privilegeClass }
    } finally {
      if (open) await client.query('ROLLBACK').catch(() => undefined)
      client.release()
    }
  }

