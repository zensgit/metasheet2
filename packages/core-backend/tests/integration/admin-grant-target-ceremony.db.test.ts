async function dropOwned(statements: string[]): Promise<void> {
  const failures: string[] = []
  for (const statement of statements) {
    try {
      await q(statement)
    } catch (error) {
      failures.push(messageOf(error) || 'cleanup failed')
    }
  }
  if (failures.length > 0) throw new Error(failures.join('; '))
}

