    const { world, session } = await seedWorld()
    const counts = { exchange: 0, profile: 0 }
    const fetchFn = providerFetch(world.openId, 'union-9', counts)
    const ticket = await started(world, session)
    let releaseHold = (): void => {}
    let released = false
    const hold = new Promise<void>((resolve) => {
      releaseHold = () => {
        if (released) return
        released = true
        resolve()
      }
    })
    const state: ClaimPauseState = { hold, firstPid: null, rootPids: [] }
    const transaction = claimPauseRunner(state)
    const run = () => completeCurrentAppCeremony(
      preflight(),
      { browserToken: ticket.browserToken, code: 'auth-code', state: ticket.state },
      session,
      { fetchFn, transaction },
    )
    let firstSettled = false
    const first = run().finally(() => {
      firstSettled = true
    })
    let second: ReturnType<typeof run> | undefined
    let secondSettled = false
    let proof: { locked: boolean; blockedByFirst: boolean } | null = null
    try {
      await untilObserved(() => {
        if (state.firstPid !== null) return true
        if (firstSettled) throw new Error('claim pause was not reached')
        return false
      })
      second = run().finally(() => {
        secondSettled = true
      })
      await untilObserved(async () => {
        if (secondSettled && proof === null) throw new Error('second complete finished before a lock wait')
        const firstPid = state.firstPid
        const secondPid = state.rootPids.find((pid) => pid !== firstPid)
        if (firstPid === null || secondPid === undefined) return false
        const seen = await claimWait(firstPid, secondPid)
        if (seen?.locked === true && seen.blockedByFirst === true) {
          proof = seen
          return true
        }
        return false
      })
    } finally {
      releaseHold()
      await Promise.allSettled([first, second].filter((item) => item !== undefined))
    }
    if (!second || state.firstPid === null || proof === null) throw new Error('native lock wait was not observed')
    expect(proof).toEqual({ locked: true, blockedByFirst: true })
    const [left, right] = await Promise.all([first, second])
    const codes = [left, right].map((result) => result.success === false ? result.code : 'ok').sort()
    expect(codes).toEqual(['ceremony_exchange_spent', 'ok'])
    expect(counts).toEqual({ exchange: 1, profile: 1 })
    const evidence = await q(
      `SELECT count(*)::int AS n FROM user_external_identity_evidence WHERE connection_id = $1::uuid`,
      [world.connectionId],
    )
    expect(evidence.rows[0]?.n).toBe(1)
