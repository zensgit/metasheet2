async function installInTransaction(install: (trx: Kysely<unknown>) => Promise<void>): Promise<void> {
  await db!.transaction().execute(async (trx) => {
    await pinKysely(trx)
    await install(trx)
  })
}

async function installBumpCounters(): Promise<void> {
  await q(`
    CREATE TABLE ceremony_bump_counts (
      name text PRIMARY KEY,
      n bigint NOT NULL
    );
    INSERT INTO ceremony_bump_counts (name, n) VALUES ('integration', 0), ('identity', 0);
    CREATE FUNCTION a_count_integration() RETURNS trigger
    LANGUAGE plpgsql AS $bump$
    BEGIN
      UPDATE ceremony_bump_counts SET n = n + 1 WHERE name = 'integration';
      RETURN NULL;
    END
    $bump$;
    CREATE TRIGGER a_count_integration
      AFTER UPDATE ON directory_integrations
      FOR EACH ROW EXECUTE FUNCTION a_count_integration();
    CREATE FUNCTION a_count_identity() RETURNS trigger
    LANGUAGE plpgsql AS $bump$
    BEGIN
      UPDATE ceremony_bump_counts SET n = n + 1 WHERE name = 'identity';
      RETURN NULL;
    END
    $bump$;
    CREATE TRIGGER a_count_identity
      AFTER UPDATE ON user_external_identities
      FOR EACH ROW EXECUTE FUNCTION a_count_identity();
  `)
}

