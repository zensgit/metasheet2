function contextForSid(userId: string, sid: string, org: string | null): AuthenticatedSessionContext {
  const token = authService.createToken(
    {
      id: userId,
      email: null,
      name: userId,
      role: 'member',
      permissions: [],
      created_at: new Date(),
      updated_at: new Date(),
      ...(org ? { tenantId: org } : {}),
    },
    { sid },
  )
  const context = readAuthenticatedSessionContext({
    user: { id: userId },
    ...(org ? { authenticatedTenantId: org } : {}),
    headers: { authorization: `Bearer ${token}` },
  } as unknown as Request)
  if (!context) throw new Error('genuine session context was not minted')
  return context
}

