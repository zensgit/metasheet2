function isClaimUpdate(text: string): boolean {
  return text.includes('SET exchange_claimed_at = clock_timestamp()')
    && text.includes('exchange_claimed_at IS NULL')
    && text.includes('consumed_evidence_id IS NULL')
    && text.includes('consumed_at IS NULL')
}

type ClaimPauseState = {
  hold: Promise<void>
  firstPid: number | null
  rootPids: number[]
}

async function readBackendPid(
  query: (sql: string, params?: unknown[]) => Promise<{ rows: Array<Record<string, unknown>> }>,
): Promise<number> {
  const confirmed = await query('SELECT pg_catalog.pg_backend_pid()::text AS pid')
  const raw = confirmed.rows[0]?.pid
  if (typeof raw !== 'string' || !/^[1-9][0-9]*$/.test(raw)) {
    throw new Error('connection backend pid was not available')
  }
  const pid = Number(raw)
  if (!Number.isSafeInteger(pid)) throw new Error('connection backend pid was not available')
  return pid
}

function claimPauseRunner(state: ClaimPauseState): AuthorizationInputTransactionRunner {
  const inner = ceremonyRunner()
  let paused = false
  return (handler) => inner(async (client) => {
    const connectedPid = await readBackendPid(client.query)
    state.rootPids.push(connectedPid)
    return handler({
      __rawClient: client.__rawClient,
      query: async (text, params) => {
        const result = await client.query(text, params)
        if (!paused && result.rowCount === 1 && isClaimUpdate(text)) {
          paused = true
          const pid = await readBackendPid(client.query)
          if (pid !== connectedPid) throw new Error('backend pid did not match the connection')
          state.firstPid = pid
          await state.hold
        }
        return result
      },
    })
  })
}

async function untilObserved(ready: () => Promise<boolean> | boolean): Promise<void> {
  const deadline = Date.now() + 20000
  for (;;) {
    if (await ready()) return
    if (Date.now() >= deadline) throw new Error('native lock wait was not observed')
    await new Promise<void>((resolve) => {
      setImmediate(resolve)
    })
  }
}

async function claimWait(firstPid: number, secondPid: number): Promise<{ locked: boolean; blockedByFirst: boolean } | null> {
  const result = await adminPool!.query(
    `SELECT activity.wait_event_type = 'Lock' AS locked,
            $2::int = ANY(pg_catalog.pg_blocking_pids(activity.pid)) AS blocked_by_first
       FROM pg_catalog.pg_stat_activity AS activity
      WHERE activity.pid = $1::int`,
    [secondPid, firstPid],
  )
  const row = result.rows[0]
  if (!row) return null
  return { locked: row.locked === true, blockedByFirst: row.blocked_by_first === true }
}

