async function started(world: World, session: AuthenticatedSessionContext, fetchFn?: typeof fetch) {
  const result = await startCurrentAppCeremony(preflight(), { connectionId: world.connectionId }, session, deps(fetchFn))
  expect(result.success).toBe(true)
  if (!result.success) throw new Error('start failed')
  const url = new URL(result.data.url)
  expect(`${url.origin}${url.pathname}`).toBe('https://login.dingtalk.com/oauth2/auth')
  expect(url.searchParams.get('client_id')).toBe(world.appKey)
  expect(url.searchParams.get('response_type')).toBe('code')
  expect(url.searchParams.get('scope')).toBe('openid')
  expect(url.searchParams.get('prompt')).toBe('consent')
  expect(url.searchParams.get('redirect_uri')).toBe(REDIRECT)
  const state = url.searchParams.get('state')
  expect(state).toBeTruthy()
  expect(state).not.toBe(result.browserToken)
  expect(result.data.url.includes(world.appSecret)).toBe(false)
  expect(result.data.url.includes('fingerprint')).toBe(false)
  return { state: String(state), browserToken: result.browserToken }
}

