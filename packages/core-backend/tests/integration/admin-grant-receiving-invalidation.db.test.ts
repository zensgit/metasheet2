type DeadlockOutcome = { side: 'A' | 'B' } & (
  | { status: 'fulfilled'; rowCount: number | null }
  | { status: 'rejected'; error: PgError }
)

type DeadlockSnapshot = {
  connection: Record<string, unknown> & { config: Record<string, unknown> }
  identities: Array<Record<string, unknown> & { id: string }>
  application: Record<string, unknown>
  bindings: Array<Record<string, unknown> & { identity_id: string }>
  evidence: Array<Record<string, unknown> & { id: string }>
}

async function readDeadlockSnapshot(
  client: PoolClient,
  seeded: Seed,
  identityIds: string[],
  evidenceIds: string[],
): Promise<DeadlockSnapshot> {
  const result = await client.query<{ state: DeadlockSnapshot }>(
    `SELECT jsonb_build_object(
       'connection', (SELECT to_jsonb(parent) FROM ${qTable('directory_integrations')} parent WHERE id = $1::uuid),
       'identities', (SELECT jsonb_agg(to_jsonb(parent) ORDER BY id) FROM ${qTable('user_external_identities')} parent WHERE id = ANY($2::uuid[])),
       'application', (SELECT to_jsonb(pin) FROM ${qTable('directory_connection_application_pins')} pin WHERE connection_id = $1::uuid),
       'bindings', (SELECT jsonb_agg(to_jsonb(pin) ORDER BY identity_id) FROM ${qTable('user_external_identity_binding_pins')} pin WHERE identity_id = ANY($2::uuid[])),
       'evidence', (SELECT jsonb_agg(
         (to_jsonb(evidence) - 'revoked_at') || jsonb_build_object('revoked', revoked_at IS NOT NULL)
         ORDER BY id
       ) FROM ${qTable('user_external_identity_evidence')} evidence WHERE id = ANY($3::text[]))
     ) AS state`,
    [seeded.connectionId, identityIds, evidenceIds],
  )
  return result.rows[0].state
}

