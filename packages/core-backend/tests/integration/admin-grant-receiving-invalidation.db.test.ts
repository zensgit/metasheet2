function kyselyOnOpenClient(client: PoolClient): Kysely<unknown> {
  const bound = {
    query: (text: string, values?: unknown[]) => client.query(text, values),
    release: () => undefined,
  }
  return new Kysely<unknown>({
    dialect: new PostgresDialect({
      pool: {
        connect: () => Promise.resolve(bound),
        end: () => Promise.resolve(),
      } as Pool,
    }),
  })
}

type PausedDown = {
  db: Kysely<unknown>
  release: () => void
  paused: () => boolean
  forwardedDrop: () => boolean
}

function pauseDownAfterFinalAccessExclusive(client: PoolClient): PausedDown {
  let openGate: () => void = () => undefined
  let opened = false
  const gate = new Promise<void>((resolve) => {
    openGate = resolve
  })
  const release = () => {
    if (opened) return
    opened = true
    openGate()
  }
  let holdFollowing = false
  let sawDrop = false
  const bound = {
    query: async (text: string, values?: unknown[]) => {
      if (holdFollowing) await gate
      if (text.includes('DROP TRIGGER') || text.includes('DROP FUNCTION')) sawDrop = true
      const result = await client.query(text, values)
      if (
        text.includes('LOCK TABLE')
        && text.includes('IN ACCESS EXCLUSIVE MODE')
        && text.includes('"user_external_identity_evidence"')
      ) {
        holdFollowing = true
      }
      return result
    },
    release: () => undefined,
  }
  return {
    db: new Kysely<unknown>({
      dialect: new PostgresDialect({
        pool: {
          connect: () => Promise.resolve(bound),
          end: () => Promise.resolve(),
        } as Pool,
      }),
    }),
    release,
    paused: () => holdFollowing && !opened,
    forwardedDrop: () => sawDrop,
  }
}

