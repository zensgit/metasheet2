function poolPid(): number {
  const pid = durable.connectPids.at(-1)
  if (!Number.isInteger(pid)) throw new Error('pool connect pid was not recorded before root work')
  return pid as number
}

function settle<T>(work: Promise<T>): Settled<T> {
  return work.then(
    (value) => ({ ok: true as const, value }),
    (error: unknown) => ({ ok: false as const, error }),
  )
}

function usersDdl(kind: ColumnKind): string {
  const permissions = kind === 'text[]' ? 'text[]' : kind
  return `CREATE TABLE users (
    id text PRIMARY KEY,
    name text,
    email text,
    username text,
    mobile text,
    activation_status text,
    role text,
    is_active boolean,
    access_generation bigint,
    deleted_at timestamptz,
    purged_at timestamptz,
    permissions ${permissions},
    updated_at timestamptz
  )`
}

