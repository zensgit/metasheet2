      expect(row(seen.users, 'n1')?.role).toBe('user')
      expect(row(seen.events, 't1', 'local_user_id')).toMatchObject({ status: 'superseded', resolved_by: 'a1', resolve_note: REASON })
      expect(row(seen.events, 'n1', 'local_user_id')).toMatchObject({ status: 'applied', resolved_by: null, resolve_note: null })
      expect(row(seen.effects, 't1', 'local_user_id')?.status).toBe('superseded')
      expect(row(seen.effects, 'n1', 'local_user_id')?.status).toBe('applied')
